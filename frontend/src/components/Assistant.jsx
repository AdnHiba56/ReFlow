import { useEffect, useRef, useState } from "react";
import Composer from "./Composer.jsx";
import PlanCard from "./PlanCard.jsx";
import SegmentOverlay from "./SegmentOverlay.jsx";
import { mediaUrl } from "../api.js";
import { PencilIcon } from "./icons.jsx";

const EDIT_MAX_CHARS = 2000;

const DOWNLOAD_EXTENSIONS = {
  "image/png": "png",
  "image/jpeg": "jpg",
  "image/webp": "webp",
  "image/gif": "gif",
};

function downloadFileName(mime) {
  return `reflow-image.${DOWNLOAD_EXTENSIONS[mime] || "png"}`;
}

// Generated/edited image: stable backend reference first, in-memory
// preview as fallback, explicit expiry notice when neither loads.
function PersistedImage({ message, sending, onRequestEdit, conversationId }) {
  const src = message.mediaId ? mediaUrl(message.mediaId) : message.imagePreview;
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    setFailed(false);
  }, [src]);
  if (!src || failed) {
    return (
      <div className="bubble assistant">
        <p>Generated image — preview expired, regenerate it if needed.</p>
        {message.imagePrompt ? <p className="muted">{message.imagePrompt}</p> : null}
      </div>
    );
  }
  return (
    <div className="bubble assistant image-bubble">
      <img
        className="message-image"
        src={src}
        onError={() => setFailed(true)}
        alt={message.imagePrompt || "Image generated by ReFlow"}
      />
      {message.imagePrompt ? <p className="muted">{message.imagePrompt}</p> : null}
      <span className="image-actions">
        <a
          className="image-download"
          href={src}
          download={downloadFileName(message.mediaMime || message.imageMime)}
        >
          Download
        </a>
        {typeof onRequestEdit === "function" && (
          <button
            type="button"
            className="secondary small"
            disabled={sending}
            onClick={() => onRequestEdit(conversationId, message.id)}
            title="Edit this image from an instruction"
          >
            Edit image
          </button>
        )}
      </span>
    </div>
  );
}

export default function Assistant({
  conversation,
  plans,
  sending,
  mode,
  onSend,
  onRetry,
  onEditMessage,
  onToggleStep,
  onNewChat,
  onModeChange,
  onImageChange,
  imageEpoch,
  onGenerateImage,
  onGenerateModeChange,
  generateEpoch,
  onEditImage,
  allowEditImage,
  imageSeed,
  onRequestEdit,
  onSegmentImage,
  allowSegmentImage,
}) {
  const bottomRef = useRef(null);
  const messages = conversation ? conversation.messages : [];
  const [editingId, setEditingId] = useState(null);
  const [editDraft, setEditDraft] = useState("");
  const conversationId = conversation?.id;

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ block: "end" });
  }, [messages, sending, conversationId]);

  useEffect(() => {
    setEditingId(null);
    setEditDraft("");
  }, [conversationId]);

  function cancelEditing() {
    setEditingId(null);
    setEditDraft("");
  }

  function submitEdit(messageId) {
    if (typeof onEditMessage === "function" && editDraft.trim()) {
      onEditMessage(conversationId, messageId, editDraft);
    }
    cancelEditing();
  }

  if (!conversation) {
    return (
      <div className="view">
        <header className="view-head">
          <h2>AI Assistant</h2>
          <p className="muted">No conversation open.</p>
        </header>
        <section className="card">
          <div className="empty">
            <p className="empty-title">Start a new conversation</p>
            <p className="muted">Each message generates a real plan via the ReFlow backend.</p>
            <button type="button" className="primary" onClick={onNewChat}>
              New conversation
            </button>
          </div>
        </section>
      </div>
    );
  }

  function renderMessage(message) {
    if (message.role === "user") {
      // Texte vide = image seule ; après rechargement, l'aperçu mémoire a
      // disparu et seul l'indicateur subsiste (Base64 jamais persisté).
      const body =
        !message.text && !message.imagePreview ? (
          <p className="bubble user">Image sent</p>
        ) : (
          <div className="bubble user">
            {message.imagePreview ? (
              <img className="message-image" src={message.imagePreview} alt="Image sent" />
            ) : null}
            {message.text ? <p>{message.text}</p> : null}
            {message.edited ? (
              <span className="edit-mark" title={message.previousText || "Edited"}>
                edited
              </span>
            ) : null}
          </div>
        );
      return (
        <>
          {body}
          {typeof onEditMessage === "function" && (
            <button
              type="button"
              className="icon-button ghost edit-button"
              onClick={() => {
                setEditingId(message.id);
                setEditDraft(message.text || "");
              }}
              disabled={sending}
              title="Edit and resend this message"
              aria-label="Edit this message"
            >
              <PencilIcon />
            </button>
          )}
        </>
      );
    }
    if (message.kind === "error") {
      return (
        <div className="bubble error" role="alert">
          <p>{message.text}</p>
          <button
            type="button"
            className="secondary small"
            disabled={sending}
            onClick={() => onRetry(conversation.id, message.id)}
          >
            Retry
          </button>
        </div>
      );
    }
    if (message.kind === "plan") {
      const entry = plans.find((plan) => plan.id === message.entryId);
      if (!entry) {
        return <p className="bubble assistant">This plan was removed from My plans.</p>;
      }
      return (
        <div className="bubble plan-bubble">
          <PlanCard entry={entry} onToggleStep={onToggleStep} showRequest={false} />
        </div>
      );
    }
    if (message.kind === "image") {
      return (
        <PersistedImage
          message={message}
          sending={sending}
          onRequestEdit={onRequestEdit}
          conversationId={conversation.id}
        />
      );
    }
    if (message.kind === "segment") {
      // Géométrie jamais persistée : après rechargement, seul le concept subsiste.
      if (!message.imagePreview || !message.segmentImage || !Array.isArray(message.segmentMatches)) {
        return (
          <div className="bubble assistant">
            <p>Segmentation expired, run it again if needed.</p>
            {message.segmentPrompt ? <p className="muted">{message.segmentPrompt}</p> : null}
          </div>
        );
      }
      return (
        <div className="bubble assistant image-bubble">
          <SegmentOverlay
            previewUrl={message.imagePreview}
            width={message.segmentImage.width}
            height={message.segmentImage.height}
            matches={message.segmentMatches}
            concept={message.segmentPrompt || ""}
            truncated={message.segmentTruncated === true}
          />
        </div>
      );
    }
    return <p className="bubble assistant">{message.text}</p>;
  }

  return (
    <div className="view chat-view">
      <header className="view-head">
        <h2>{conversation.title}</h2>
        <p className="muted">
          {mode === "chat"
            ? "Free discussion with ReFlow, with memory of the exchange."
            : "Each message generates a real plan via the ReFlow backend."}
        </p>
        <div className="mode-switch" role="group" aria-label="Conversation mode">
          <button
            type="button"
            className={mode === "plan" ? "mode-option active" : "mode-option"}
            aria-pressed={mode === "plan"}
            onClick={() => onModeChange(conversation.id, "plan")}
          >
            Action plan
          </button>
          <button
            type="button"
            className={mode === "chat" ? "mode-option active" : "mode-option"}
            aria-pressed={mode === "chat"}
            onClick={() => onModeChange(conversation.id, "chat")}
          >
            Discussion
          </button>
        </div>
      </header>

      <section className="card chat-log" aria-live="polite" aria-label="Conversation">
        {messages.length === 0 && !sending ? (
          <p className="muted">Write your first message below to get started.</p>
        ) : null}
        {messages.map((message) => (
          <div key={message.id} className={`message ${message.role}`}>
            {message.role === "user" && editingId === message.id ? (
              <div className="bubble user message-edit">
                <textarea
                  value={editDraft}
                  onChange={(event) => setEditDraft(event.target.value)}
                  rows={3}
                  maxLength={EDIT_MAX_CHARS}
                  disabled={sending}
                  aria-label="Edit your message"
                  autoFocus
                />
                <div className="message-edit-row">
                  <span className="counter" aria-live="polite">
                    {EDIT_MAX_CHARS - editDraft.length} characters left
                  </span>
                  <span className="composer-buttons">
                    <button
                      type="button"
                      className="secondary small"
                      onClick={cancelEditing}
                      disabled={sending}
                    >
                      Annuler
                    </button>
                    <button
                      type="button"
                      className="primary small"
                      onClick={() => submitEdit(message.id)}
                      disabled={sending || !editDraft.trim()}
                    >
                      Renvoyer
                    </button>
                  </span>
                </div>
              </div>
            ) : (
              renderMessage(message)
            )}
          </div>
        ))}
        {sending && (
          <div className="message assistant">
            <div className="bubble assistant typing" aria-label="ReFlow is writing a reply">
              <span aria-hidden="true" />
              <span aria-hidden="true" />
              <span aria-hidden="true" />
            </div>
          </div>
        )}
        <div ref={bottomRef} />
      </section>

      <section className="card" aria-label="Input area">
        <Composer
          id="chat-composer"
          placeholder="Describe your request…"
          sending={sending}
          sendingLabel="Generating…"
          onSend={(text, imageInfo) => onSend(conversation.id, text, imageInfo)}
          allowImage={mode === "chat"}
          onImageChange={onImageChange}
          imageEpoch={imageEpoch}
          onGenerateImage={(text) => onGenerateImage(conversation.id, text)}
          allowGenerateImage={mode === "chat"}
          onGenerateModeChange={onGenerateModeChange}
          generateEpoch={generateEpoch}
          onEditImage={(text, imageInfo) => onEditImage(conversation.id, text, imageInfo)}
          allowEditImage={mode === "chat" && allowEditImage !== false}
          imageSeed={imageSeed}
          onSegmentImage={(text, imageInfo) => onSegmentImage(conversation.id, text, imageInfo)}
          allowSegmentImage={mode === "chat" && allowSegmentImage !== false}
        />
      </section>
    </div>
  );
}
